-- ------------------------------------------------------------
-- 5. FUNÇÃO PARA SABER SE O USUÁRIO É ADMIN
-- ------------------------------------------------------------

create or replace function public.is_admin()
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (
    select 1
    from public.clientes
    where user_id = auth.uid()
      and is_admin = true
  );
$$;


-- ------------------------------------------------------------
-- 6. FUNÇÃO PARA SABER SE O CLIENTE É DONO DO CADASTRO
-- ------------------------------------------------------------

create or replace function public.owns_client(client_id bigint)
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (
    select 1
    from public.clientes
    where id = client_id
      and user_id = auth.uid()
  );
$$;


