-- ============================================================
-- 9. POLÍTICAS — CLIENTES
-- ============================================================

create policy "clientes_select_own"
on public.clientes
for select
to authenticated
using (
  user_id = auth.uid()
  or public.is_admin()
);

create policy "clientes_insert_own"
on public.clientes
for insert
to authenticated
with check (
  user_id = auth.uid()
);

create policy "clientes_update_own"
on public.clientes
for update
to authenticated
using (
  user_id = auth.uid()
  or public.is_admin()
)
with check (
  user_id = auth.uid()
  or public.is_admin()
);

create policy "clientes_admin_all"
on public.clientes
for all
to authenticated
using (
  public.is_admin()
)
with check (
  public.is_admin()
);


